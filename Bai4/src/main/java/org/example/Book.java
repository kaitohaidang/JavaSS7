public class Book {
    // Thuộc tính
    public String title;
    public String author;
    public double price;

    // Phương thức in thông tin
    public void printInfo() {
        System.out.println("Title: " + title);
        System.out.println("Author: " + author);
        System.out.println("Price: " + price);
    }
}
